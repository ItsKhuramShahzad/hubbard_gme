"""
All tables of the paper in one run: U/t (ground state, excited singlet), V/t, doped K and doped U/t.

C_GME and purity: read from the PKLs of the figures.
E_0, S, S_z, g, gaps and omega_n: recomputed with the package ED (tables_lib.build_states), same sector as the run.

Run from the hubbard_gme repo:
    PYTHONPATH=src python /mnt/d/Dropbox/PhDWork/hubbard_gme/audit_reports/table_tests/make_tables.py
Writes all_tables.tex next to this file.
"""
import os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tables_lib import SPECS, ZERO_TRACE, load, point, build_states, omega, spin_info, rho_s
from hubbard_gme.metrics import compute_entropy

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "all_tables.tex")
CG = r"$\mathcal{C}_{\mathrm{GME}}$"
PUR = r"$\mathrm{Tr}\,\rho_s^2$"
ENT = r"$S_{\rm vN}$"


def settings(m, r=None):
    txt = rf" $q$ was scanned from $r$ to $r+{m['k_max_extra']}$ and the lowest value kept."
    if r is not None and "convergence" not in r:
        txt += r" The per-point $q$ was not stored for this run (--)."
    return txt


def sci(x):
    if x < ZERO_TRACE:
        return "--"
    if x >= 0.0995:
        return f"{x:.3f}"
    if x >= 0.000995:                                   # plain decimal, 3 significant digits
        return f"{x:.{2 - int(np.floor(np.log10(x)))}f}"
    m, e = f"{x:.2e}".split("e")
    return rf"${m}\times10^{{{int(e)}}}$"


def fgap(g):
    return f"{g:.3f}" if g >= 0.001 else sci(g)


def frac(v):
    v2 = int(round(2 * abs(v)))
    return str(v2 // 2) if v2 % 2 == 0 else f"{v2}/2"


def fS(S):
    return ", ".join(frac(s) for s in S)


def fSz(Szs):
    """S_z values present in the degenerate level, e.g. 0 ; \pm1/2 ; 0,\pm1."""
    mags = sorted({abs(v) for v in Szs})
    parts = []
    for a in mags:
        both = (a in Szs) and (-a in Szs)
        parts.append(frac(a) if a == 0 else (r"\pm" if both else ("" if a in Szs else "-")) + frac(a))
    return "$" + ",".join(parts) + "$"


def long_table(rows, xlab, caption, label):
    """One row per (x, n), as Table I of the paper: x, S, g, n, omega_n, gamma_n, S_vN, C_GME."""
    lines = []
    for bi, (x, S, g, ns, w, P, Sv, C, R) in enumerate(rows):
        for j, n in enumerate(ns):
            lead = f"{x:g} & {fS(S)} & {g}" if j == 0 else " & & "
            vals = (["--"] * 7 if w[n] < ZERO_TRACE else
                    [f"{P[n]:.3f}", f"{Sv[n]:.3f}"] + [str(v) for v in R[n]] + [f"{C[n]:.3f}"])
            lines.append(f"{lead} & {n} & {sci(w[n])} & " + " & ".join(vals) + r" \\")
        if bi < len(rows) - 1:
            lines.append(r"\hline")
    lines[-1] = lines[-1][:-3]
    return (r"\begin{table*}" "\n" rf"\caption{{{caption}}}" "\n" rf"\label{{tab:{label}}}" "\n"
            r"\begin{ruledtabular}" "\n" r"\begin{tabular}{cccccccccccc}" "\n"
            + rf"{xlab} & $S$ & $g$ & $n$ & $\omega_n$ & $\gamma_n$ & $S_{{\rm vN}}$ & $r$ & $q$ & $N_r$ & $N_{{\rm it}}$ & {CG} \\" "\n" r"\hline" "\n"
            + "\n".join(lines) + "\n" r"\end{tabular}" "\n" r"\end{ruledtabular}" "\n" r"\end{table*}" "\n")


COLS = (r" For each point the table reports: the total spin $S$ of the state; its degeneracy $g$; the detection probability "
        r"$\omega_n$, corresponding to the trace of the $n$BRDM; the purity $\gamma_n$ and the von Neumann entropy "
        r"$S_{\rm vN}=-\mathrm{Tr}\,\rho_s\ln\rho_s$ of the normalized spin state; the rank $r$ of $\rho_s$; the number $q$ of "
        r"states in the decomposition that gives " + CG + r"; the number $N_r$ of random restarts and the maximum number "
        r"$N_{\rm it}$ of iterations of each restart. For a pure $\rho_s$ ($\gamma_n=1$) " + CG + r" is computed exactly and no "
        r"optimisation is needed. For $n=2$ (nearest neighbours) " + CG + r" coincides with the Wootters concurrence.")

out = ["% generated by audit_reports/table_tests/make_tables.py",
       "% C_GME, purity, entropy from the PKLs of the figures (entropy of Fig. 1 L=6 rebuilt: that PKL has none)",
       "% S, g and omega_n from the package ED; Fig. 1 L=6 PKL has no per-point q", ""]
for spec in SPECS:
    m, r, sp, xs = load(spec)
    ns_all = [n for n in m["n_values"]]
    sector = (r" The calculation uses the $S_z=0$ sector, so $g$ counts the states with $S_z=0$." if sp else "")
    print(f"\n== {spec['key']}  ({spec['fig']} {spec['panel']}, sector {'Sz=0' if sp else 'full'})", flush=True)
    rows = []
    for x in spec["rows"]:
        i = int(np.argmin(np.abs(xs - x)))
        assert abs(xs[i] - x) < 1e-6, (spec["key"], x)
        L, K, t, U, V = point(spec, m, r, sp, x)
        psis, E, info = build_states(spec, L, K, t, U, V, sp, int(r.get("singlet_k", 16) or 16))
        S, Sz = spin_info(psis, L, K, sp)
        Ex = info.get("energy", E[0])
        ns = [n for n in ns_all if 2 <= n <= K]
        w = {n: omega(psis, L, K, n, sp) for n in ns}
        C = {n: float(r["C_GME"][n][i]) for n in ns}
        P = {n: float(r["purity"][n][i]) for n in ns}
        if "entropy" in r:
            Sv = {n: float(r["entropy"][n][i]) for n in ns}
        else:                                   # Fig. 1 L=6 PKL stores no entropy: rebuild rho_s, check its purity
            Sv = {}
            for n in ns:
                rho = rho_s(psis, L, K, n, sp)
                assert abs(np.real(np.sum(np.abs(rho) ** 2)) - P[n]) < 1e-8 or w[n] < ZERO_TRACE, (spec["key"], x, n)
                Sv[n] = float(compute_entropy(rho))
        R = {}                                  # GCG record of each point: rank r, q of the best decomposition, N_r, N_it
        for n in ns:
            c = (r.get("convergence") or {}).get(n, [None] * len(xs))[i]
            if isinstance(c, dict) and c.get("solver") == "pure":
                R[n] = (1, "--", "--", "--")    # pure state: exact formula, no optimisation
            elif isinstance(c, dict):
                R[n] = (c["rank"], c["k_converged"], c["n_restarts_effective"], c["max_iter"])
            elif P[n] > 1 - 1e-6:
                R[n] = (1, "--", "--", "--")
            else:                               # Fig. 1 L=6 PKL keeps no per-point record: rank from rho_s, q not stored
                ev = np.linalg.eigvalsh(rho_s(psis, L, K, n, sp))
                R[n] = (int(np.sum(ev > 1e-10)), "--", m["n_restarts"], m["max_iter"])
        rows.append((x, S, info["g"], ns, w, P, Sv, C, R))

    L = m["L"]
    if spec["kind"] == "K":
        cap = (r"Ground state of the doped Hubbard ring, $L=8$, $U/t=10$, $V=0$, as a function of the number of electrons $K$ "
               r"(data of Fig.~\ref{fig06})." + COLS + r"" + settings(m))
        out.append(long_table(rows, "$K$", cap, spec["key"]))
        continue
    if spec["key"].startswith("uscan_gs"):
        cap = (rf"Ground state of the Hubbard ring with $L=K={L}$, $V=0$, as a function of $U/t$ (data of Fig.~\ref{{fig01}})."
               + COLS + sector + settings(m, r))
    elif spec["key"].startswith("uscan_es"):
        cap = (rf"First excited singlet of the Hubbard ring with $L=K={L}$, $V=0$, as a function of $U/t$ (data of Fig.~\ref{{fig02}})."
               + COLS + settings(m))
    elif spec["kind"] == "V":
        cap = (rf"Ground state of the extended Hubbard ring with $L=K={L}$, $U/t=10$, as a function of $V/t$ (data of Fig.~\ref{{fig04}})."
               + COLS + r" Entries marked -- have $\omega_n=0$ (below $10^{-14}$): $\rho_s$ is not defined and the point is not shown in the figure."
               + settings(m))
    else:
        cap = (r"Ground state of the doped Hubbard ring, $L=8$, $K=6$, $V=0$, as a function of $U/t$ (data of Fig.~\ref{fig05})."
               + COLS + sector + settings(m, r))
    out.append(long_table(rows, "$V/t$" if spec["kind"] == "V" else "$U/t$", cap, spec["key"]))

open(OUT, "w").write("\n".join(out))
print("\nwritten", OUT)
